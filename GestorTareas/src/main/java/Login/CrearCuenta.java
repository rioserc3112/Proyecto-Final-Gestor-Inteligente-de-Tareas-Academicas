    private boolean comprobarDatos(){
        //Se comprueba que los campos no esten vacios y si estan se pone el label en rojo
        boolean datosCorrectos = true;
        
        //Nombre
        if(txtNombre.getText().isBlank()){
            lblNombre.setForeground(Color.red);
            datosCorrectos = false;
        }
        else{
            lblNombre.setForeground(Color.black);
        }
        
        //Apellido
        if(txtApellido1.getText().isBlank()){
            lblApellido1.setForeground(Color.red);
            datosCorrectos = false;
        }
        else{
            lblApellido1.setForeground(Color.black);
        }

        
        //-----------------Se comprueba que el correo y contrasena sean validos-----------------
        
        boolean CorreoCorrecto = comprobarCorreo();
        boolean ContrasenaCorrecto = comprobarContrasena();
        
        if(CorreoCorrecto && ContrasenaCorrecto){
            //Se crea usuario 
            Usuario user = new Usuario();
            
            user.setCorreo(txtCorreo.getText());
            user.setContrasena(txtContrasena1.getText());
            user.setNombre(txtNombre.getText());
            user.setApellido1(txtApellido1.getText());
            user.setApellido2(txtApellido2.getText());
            
            agregarUsuario(user);
            
        }
        
                
        return datosCorrectos;
        
    }
    
    public boolean comprobarCorreo(){
        if(txtCorreo.getText().isBlank()){
            lblCorreo.setForeground(Color.red);
            return false;
        }
        else{
            txtAdvertenciaCorreo.setVisible(false);
            lblCorreo.setForeground(Color.black);
            //Que tenga @

            if(!txtCorreo.getText().contains("@")){
                txtAdvertenciaCorreo.setVisible(true);
                txtAdvertenciaCorreo.setText("Correo es invalido");
                lblCorreo.setForeground(Color.red);
                return false;
            }
            //Que no tenga espacios
            if(txtCorreo.getText().contains(" ")){
                txtAdvertenciaCorreo.setVisible(true);
                txtAdvertenciaCorreo.setText("Correo no puede contener espacios");
                lblCorreo.setForeground(Color.red);
                return false;
            }

            //Que termine en .com
            if(!txtCorreo.getText().endsWith(".com")){
                txtAdvertenciaCorreo.setVisible(true);
                txtAdvertenciaCorreo.setText("Correo debe de terminar en '.com'");
                lblCorreo.setForeground(Color.red);
                return false;
            }

            //Que correo tenga algun dominio
            //Que termine en .com
            if(txtCorreo.getText().endsWith("@.com")){
                txtAdvertenciaCorreo.setVisible(true);
                txtAdvertenciaCorreo.setText("Correo es invalido");
                lblCorreo.setForeground(Color.red);
                return false;
            }
        }
        
        
    txtAdvertenciaCorreo.setVisible(false);    
    return true;
    } //Fin comprobar correo
    
    
    public boolean comprobarContrasena(){
        
        //Que tenga más de 4 caracteres
        if(txtContrasena1.getText().length() < 4){
            txtAdvertenciaContrasena.setText("Contraseña debe tener más de 4 caracteres");
            txtAdvertenciaContrasena.setVisible(true);
            return false;
            
        }
            
        //Se comprueba que la contraseña sea igual al correo
        if(!txtCorreo.getText().isBlank()){
            if(txtContrasena1.getText().contains(txtCorreo.getText())){
                txtAdvertenciaContrasena.setText("La Contraseña no puede contener el correo");
                txtAdvertenciaContrasena.setVisible(true);
                return false;

            }
        }
        else{
            txtAdvertenciaContrasena.setVisible(false);
        }
            
        //Se comprueba que la contraseña sea igual
        if(!txtContrasena1.getText().equals(txtContrasena2.getText())){
            txtAdvertenciaContrasena.setText("La Contraseña no coincide");
            txtAdvertenciaContrasena.setVisible(true);
            return false;
        }
        else{
            txtAdvertenciaContrasena.setVisible(false);
        }
        
        return true;
        
    } //Fin comprobar contraseña
    
    public void agregarUsuario(Usuario user){

        
       try {
           String sql = "INSERT INTO usuarios VALUES (?,?,?,?,?)";
           
            PreparedStatement pstmt = conectar.Conectar().prepareStatement(sql); 
            pstmt.setString(1, user.getCorreo());
            pstmt.setString(2, user.getContrasena());
            pstmt.setString(3, user.getNombre());
            pstmt.setString(4, user.getApellido1());
            pstmt.setString(5,user.getApellido2());
            
            pstmt.executeUpdate();
            JOptionPane.showMessageDialog(null, "¡Se agregó el usuario correctamente!", "Agregado", JOptionPane.INFORMATION_MESSAGE);
            
       } 
       catch (SQLException e) 
        {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "No se puede agregar una fila ya existente", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
       
       catch (IllegalArgumentException e) 
        {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "La fecha ingresada es incorrecta", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
       
        
    }
    
